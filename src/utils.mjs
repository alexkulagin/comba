			export const isObject = value => typeOf(value) === '[object Object]';


		// IS PLAIN
		// ▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔▔

			export const isPlain = (value) =>
			{
				if (!value || !isObject(value)) {
					return false;
				}

				const proto = Object.getPrototypeOf(value);

				if (!proto) {
					return true;
				}

				const ƒ = hasKey(proto, 'constructor') && proto.constructor;

				return typeof ƒ === 'function' && ƒ instanceof ƒ && Function.prototype.toString.call(ƒ) === Function.prototype.toString.call(Object);
			};



